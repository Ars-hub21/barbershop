/* ---------- Вспомогательные функции (используются панелью барберов) ---------- */

// Найти запись мастера по его имени (как оно хранится в Google Таблице).
// Ищем среди ВСЕХ мастеров (обеих версий), чтобы старые записи и история
// не ломались при переключении версии сайта.
function getMasterByName(name) {
  return ALL_MASTERS.find(function (m) { return m.name === name; });
}

// Получить "ключ" мастера (латиница для id элементов) по имени.
// Если мастер не найден в списке (например, был удалён после того как
// по нему уже остались старые заказы) — подстраховываемся транслитерацией,
// чтобы страница не падала.
function getMasterKey(name) {
  const found = getMasterByName(name);
  if (found) return found.key;
  return String(name || 'master').replace(/[^a-zA-Z0-9]/g, '') || 'master';
}
