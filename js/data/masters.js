// Полный список мастеров ОБЕИХ версий — используется только внутренней
// панелью барберов (barber_panel/), чтобы персонал всегда видел и мог
// управлять записями по всем мастерам сразу, независимо от того, какую
// версию сайта сейчас видят клиенты.
const ALL_MASTERS = [].concat(MASTERS_BY_GENDER.masculine, MASTERS_BY_GENDER.feminine);

// Список мастеров ТЕКУЩЕЙ версии сайта — то, что видят клиенты. Определяется
// переменной SALON_THEME из js/core/site-config.js (подключайте этот файл
